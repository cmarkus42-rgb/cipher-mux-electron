/**
 * Wann ist der Worker fertig? (Spec §7, Schritt 5)
 *
 * Zwei Signale, weil keines allein trägt: REPORT.md sagt „ich halte mich für
 * fertig“, das Idle-Ereignis sagt „der Zug ist zu Ende“. Ein Report mitten im
 * Zug ist möglich, ein Idle zwischen zwei Zügen auch. Fällt das Idle-Ereignis
 * aus (anderer Name in einer neuen opencode-Version — still, wie alles dort),
 * trägt die Ruhezeit.
 *
 * **opencode 2 (gemessen an 2.0.29, 2026-10-14):** Das Plugin ist eine Definition
 * `{ id, setup }`, das Ereignis kommt aus `ctx.event.subscribe()`. Das Zugende
 * heißt dort `session.execution.succeeded` (gemessen); `…failed` und
 * `…interrupted` stehen im Binary. `session.idle` (1.x: genau einmal am Zugende)
 * kam im `opencode run`-Lauf nicht an, steht aber als Eventname im Binary — ob die
 * TUI es sendet, ist ungemessen, deshalb hören wir auf alle vier. Ein Zug, der
 * fehlschlägt oder unterbrochen wird, ist für den Läufer ebenfalls „untätig":
 * ohne Report wertet er das als Hänger, und genau das soll er schnell tun.
 */

export const IDLE_SIGNAL_FILENAME = '.cipher-mux-idle'
export const IDLE_PLUGIN_FILENAME = 'cipher-mux-idle.js'
export const IDLE_PLUGIN_ID = 'cipher-mux.idle'
/** Ereignisse, die das Ende eines Zuges melden. Spec 2026-10-14 §2.5. */
export const IDLE_EVENT_TYPES = [
  'session.execution.succeeded',
  'session.execution.failed',
  'session.execution.interrupted',
  'session.idle',
] as const

export function buildIdlePlugin(signalFile: string): string {
  return `// Generated by cipher-mux (local-factory/worker-done.ts). Do not edit.
// opencode 2: default-export a plugin DEFINITION ({ id, setup }).
import * as fs from 'node:fs'

const SIGNAL = ${JSON.stringify(signalFile)}
const TYPES = new Set(${JSON.stringify(IDLE_EVENT_TYPES)})

export default {
  id: ${JSON.stringify(IDLE_PLUGIN_ID)},
  setup(ctx) {
    const controller = new AbortController()
    void (async () => {
      try {
        for await (const ev of ctx.event.subscribe({ signal: controller.signal })) {
          try {
            if (ev && typeof ev.type === 'string' && TYPES.has(ev.type)) {
              fs.writeFileSync(SIGNAL, String(Date.now()), 'utf-8')
            }
          } catch {
            // Signal, keine Zusage — die Ruhezeit trägt ohne.
          }
        }
      } catch {
        // Strom beendet oder abgebrochen.
      }
    })()
    return () => controller.abort()
  },
}
`
}

export type WorkerState = 'arbeitet' | 'fertig' | 'haengt'

export interface WorkerObservation {
  now: number
  startedAt: number
  reportMtime: number | null
  idleSignalAt: number | null
  lastActivityAt: number
}

export function classifyWorker(
  o: WorkerObservation,
  cfg: { quietMs: number; timeoutMs: number; stallMs: number },
): WorkerState {
  if (o.now - o.startedAt > cfg.timeoutMs) return 'haengt'
  const quiet = o.now - o.lastActivityAt
  if (o.reportMtime !== null) {
    if (o.idleSignalAt !== null && o.idleSignalAt >= o.reportMtime) return 'fertig'
    if (quiet > cfg.quietMs) return 'fertig'
    return 'arbeitet'
  }
  // Untätig ohne Report: am Ausgabelimit endet das Modell still (Spec §10a.2).
  if (o.idleSignalAt !== null && quiet > cfg.quietMs) return 'haengt'
  if (quiet > cfg.stallMs) return 'haengt'
  return 'arbeitet'
}
